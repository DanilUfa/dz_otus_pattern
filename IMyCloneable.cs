namespace PrototypePattern;

/// <summary>
/// Создаёт независимую глубокую копию с сохранением фактического типа объекта.
/// </summary>
/// <typeparam name="T">Тип результата клонирования.</typeparam>
/// <remarks>
/// Изменяемые объекты копии не должны разделяться с оригиналом.
/// Неизменяемые объекты, например строки, могут использоваться совместно.
/// Эти требования обеспечиваются реализацией, а не ключевым словом out.
/// </remarks>
public interface IMyCloneable<out T>
{
    /// <summary>Возвращает новый объект с данными оригинала.</summary>
    T Clone();
}
